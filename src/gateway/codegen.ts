/** One generated method, from one OpenAPI operation. */
export interface GeneratedOperation {
    operationId: string;
    method: string;
    path: string;
}

type OpenApiDoc = {
    paths?: Record<string, Record<string, { operationId?: string }>>;
};

const METHODS = ["get", "post", "put", "patch", "delete"];

/**
 * Lists the operations in an OpenAPI document.
 * @param doc the parsed openapi.json
 * @returns the operations that carry an operationId
 */
export function listOperations(doc: OpenApiDoc): GeneratedOperation[] {
    const out: GeneratedOperation[] = [];
    for (const [path, item] of Object.entries(doc.paths ?? {})) {
        for (const method of METHODS) {
            const id = item[method]?.operationId;
            if (id) out.push({ operationId: id, method, path });
        }
    }
    return out;
}

/**
 * Writes the typed client source. Each operation becomes a method named by
 * its operationId (`items.list` becomes `client.items.list(...)`), typed from
 * the `operations` interface that openapi-typescript emits next to it.
 * @param operations the operations in the document
 * @param typesImport the import path of the generated types file
 * @param sdkImport the import path of the gateway client
 * @returns TypeScript source
 */
export function generateClientSource(
    operations: GeneratedOperation[],
    typesImport = "./gateway.d.ts",
    sdkImport = "@tessellatepos/plugin-sdk/gateway",
): string {
    const groups = new Map<string, GeneratedOperation[]>();
    for (const op of operations) {
        const [group] = op.operationId.split(".");
        groups.set(group, [...(groups.get(group) ?? []), op]);
    }
    const lines = [
        "// Generated by `tessellate-gateway generate`. Do not edit.",
        `import type { operations } from ${JSON.stringify(typesImport)};`,
        `import type {`,
        `    GatewayClient,`,
        `    GatewayRequestOptions,`,
        `    OperationBody,`,
        `    OperationQuery,`,
        `    OperationResponse,`,
        `} from ${JSON.stringify(sdkImport)};`,
        "",
        "type Call<Op> = (",
        "    options?: Omit<GatewayRequestOptions, 'body' | 'query'> & {",
        "        body?: OperationBody<Op>;",
        "        query?: OperationQuery<Op>;",
        "    },",
        ") => Promise<OperationResponse<Op>>;",
        "",
        "export function createTypedClient(client: GatewayClient) {",
        "    const call = <Op>(method: string, path: string): Call<Op> =>",
        "        (options) =>",
        "            client.request(method, path, options as GatewayRequestOptions);",
        "    return {",
    ];
    for (const [group, ops] of groups) {
        lines.push(`        ${JSON.stringify(group)}: {`);
        for (const op of ops) {
            const name = op.operationId.slice(group.length + 1) || group;
            const key = JSON.stringify(op.operationId);
            lines.push(
                `            ${JSON.stringify(name)}: call<operations[${key}]>(${JSON.stringify(op.method)}, ${JSON.stringify(op.path)}),`,
            );
        }
        lines.push("        },");
    }
    lines.push("    };", "}", "");
    return lines.join("\n");
}
